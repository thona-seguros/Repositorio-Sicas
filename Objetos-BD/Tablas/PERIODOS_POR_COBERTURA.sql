DECLARE

vIDTIPOSEG  VARCHAR2(100);
vPLANCOB    VARCHAR2(100);
vCODCOBERT  VARCHAR2(100);

CURSOR C1 IS
SELECT IDTIPOSEG, PLANCOB, CODCOBERT FROM COBERTURAS_DE_SEGUROS
WHERE IDTIPOSEG='GMPR2C'
ORDER BY 3;

BEGIN

OPEN C1;
  LOOP
    fetch C1 into vIDTIPOSEG, vPLANCOB, vCODCOBERT;
