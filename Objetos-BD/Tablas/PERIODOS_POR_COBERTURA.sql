SELECT CBA.CODCIA, CBA.COD_ASEGURADO, CBA.CODEMPRESA, CBA.IDPOLIZA, CBA.IDETPOL, CBA.CODCOBERT, CBA.PLANCOB, CBA.IDTIPOSEG, 
TO_CHAR(CBA.SUMAASEG_MONEDA,'999,999,999,999.99') SUMAASEG_MONEDA,
CBA.SUMAASEG_LOCAL,
CBA.PRIMA_MONEDA, CBA.PRIMA_LOCAL, DEDUCIBLE_LOCAL,
OC_COBERTURAS_DE_SEGUROS.DESCRIPCION_COBERTURA(CBA.CODCIA, CBA.CODEMPRESA, CBA.IDTIPOSEG, CBA.PLANCOB, CBA.CODCOBERT) NOMBRECOBERTURA, ORDENIMPRESION,
PC.PERIODO_CARENCIA, PC.PERIODO_ESPERA
FROM COBERT_ACT_ASEG CBA
INNER JOIN COBERTURAS_DE_SEGUROS CS ON CS.CODCOBERT = CBA.CODCOBERT
INNER JOIN SICAS_OC.PERIODOS_POR_COBERTURA PC ON CBA.CODCOBERT = PC.CODCOBERT AND CBA.PLANCOB = PC.PLANCOB AND CBA.IDTIPOSEG = PC.IDTIPOSEG
AND CS.PLANCOB = CBA.PLANCOB
AND CS.IDTIPOSEG = CBA.IDTIPOSEG
AND CS.CODEMPRESA = CBA.CODEMPRESA
AND CS.CODCIA = CBA.CODCIA
AND CBA.CODCIA = 1
AND CBA.IDPOLIZA = $P{IDPOLIZA} 
AND CBA.IDETPOL = $P{IDETPOL} 
AND CBA.COD_ASEGURADO = $P{COD_ASEGURADO} 
UNION
SELECT CBA.CODCIA, CBA.COD_ASEGURADO, CBA.CODEMPRESA, CBA.IDPOLIZA, CBA.IDETPOL, CBA.CODCOBERT, CBA.PLANCOB, CBA.IDTIPOSEG, 
TO_CHAR(CBA.SUMAASEG_MONEDA,'999,999,999,999.99') SUMAASEG_MONEDA,
CBA.SUMAASEG_LOCAL,
CBA.PRIMA_MONEDA, CBA.PRIMA_LOCAL, DEDUCIBLE_LOCAL,
OC_COBERTURAS_DE_SEGUROS.DESCRIPCION_COBERTURA(CBA.CODCIA, CBA.CODEMPRESA, CBA.IDTIPOSEG, CBA.PLANCOB, CBA.CODCOBERT) NOMBRECOBERTURA, ORDENIMPRESION,
PC.PERIODO_CARENCIA, PC.PERIODO_ESPERA
FROM COBERT_ACT CBA 
INNER JOIN COBERTURAS_DE_SEGUROS CS ON CS.CODCOBERT = CBA.CODCOBERT
INNER JOIN SICAS_OC.PERIODOS_POR_COBERTURA PC ON CBA.CODCOBERT = PC.CODCOBERT AND CBA.PLANCOB = PC.PLANCOB AND CBA.IDTIPOSEG = PC.IDTIPOSEG
AND CS.PLANCOB = CBA.PLANCOB
AND CS.IDTIPOSEG = CBA.IDTIPOSEG
AND CS.CODEMPRESA = CBA.CODEMPRESA
AND CS.CODCIA = CBA.CODCIA
AND CBA.CODCIA = 1
AND CBA.IDPOLIZA = $P{IDPOLIZA} 
AND CBA.IDETPOL = $P{IDETPOL} 
AND CBA.COD_ASEGURADO = $P{COD_ASEGURADO} 
ORDER BY ORDENIMPRESION
