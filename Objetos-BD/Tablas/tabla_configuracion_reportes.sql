CREATE TABLE CONFIGURACION_REPORTES(
CodCia         NUMBER(14)     NOT NULL,
CodEmpresa     NUMBER(14)     NOT NULL,
Modulo         VARCHAR2(100)  NOT NULL,
Opcion         VARCHAR2(100)  NOT NULL,      
CodReporte     VARCHAR2(10)   NOT NULL,
Consecutivo    NUMBER(14)     NOT NULL,
NombreReporte  VARCHAR2(300),
NomArchivo     VARCHAR2(100),
StsReporte     VARCHAR2(10),
FecStsReporte  DATE)
TABLESPACE TS_SICASOC
PCTUSED    0
PCTFREE    10
INITRANS   1
MAXTRANS   255
STORAGE    (
            INITIAL          64K
            NEXT             1M
            MINEXTENTS       1
            MAXEXTENTS       UNLIMITED
            PCTINCREASE      0
            BUFFER_POOL      DEFAULT
           )
LOGGING 
NOCOMPRESS 
NOCACHE
NOPARALLEL
MONITORING;
/
COMMENT ON TABLE CONFIGURACION_REPORTES IS 'Tabla para registrar la configuración de reportes para Apex'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.CodCia IS 'Codigo de compañia'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.CodEmpresa IS 'Codigo de empresa'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.Modulo IS 'Nombre del módulo al que pertenece el reporte'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.Opcion IS 'Opción Dentro del Menú Donde se Encuentra el Reporte'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.CodReporte IS 'Código del Reprte'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.NombreReporte IS 'Nombre del Reporte'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.NomArchivo IS 'Nombre del Archivo del reporte sugerido'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.StsReporte IS 'Estatus del Reporte'
/
COMMENT ON COLUMN CONFIGURACION_REPORTES.FecStsReporte IS 'Fecha Estatus del Reporte'
/
