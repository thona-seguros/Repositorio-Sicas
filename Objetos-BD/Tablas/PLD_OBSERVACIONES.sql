CREATE SEQUENCE SICAS_OC.SEQ_PLD_OBSERVACIONES
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    NOMAXVALUE
    NOCYCLE
    ORDER;
/*
ID_PROCESO, IDPOLIZA, IDETPOL, TP_PERSONA, ORIGEN, IDFACTURA, FE_PROCESO, USUARIO_ACTUA -RELEVANTES
FOLIO_DENUNCIA - PREOCUPANTES
ID_PROCESO,IDPOLIZA,IDETPOL,TP_PERSONA,ORIGEN,IDFACTURA,FE_PROCESO,USUARIO_ACTUA
*/
CREATE TABLE SICAS_OC.PLD_OBSERVACIONES(
    IDPROCESO       NUMBER ,   -- 1 HISTORICO, 2 RELEVANTES, 3 PREOCUPANTES,4 INTERNAS, 5 ADMINLISTN,6 CRUCE HISTORICO 7 admriesg(emi-sin)
    IDCONSEC        NUMBER  DEFAULT SICAS_OC.SEQ_PLD_OBSERVACIONES.NEXTVAL,
    PROCESO_ACTIVI  NUMBER,
    IDPOLIZA        NUMBER,
    IDETPOL         NUMBER,
    TIPOPERSONA     VARCHAR2(20),
    LISTAORIGEN     VARCHAR2(200),
    NOMBRE          VARCHAR2(1000),
    APELLIDO_PAT    VARCHAR2(50),
    APELLIDO_MAT    VARCHAR2(50),
    RFC             VARCHAR2(15),
    IDFACTURA       NUMBER,
    NUMSINIESTRO    NUMBER  DEFAULT 0,
    FECHA_PROCESO   DATE,
    DESCRIPCION     VARCHAR2(4000),
    FECHAINSERT     DATE DEFAULT SYSDATE,
    USRINSERT       VARCHAR2(20) DEFAULT USER,
    FECHAUPDATE     DATE,
    USRUPDATE       VARCHAR2(20)
    );

CREATE UNIQUE INDEX SICAS_OC.IDX_PLD_OBSERVACIONES_1 ON
    SICAS_OC.PLD_OBSERVACIONES(IDPROCESO,IDCONSEC);

CREATE UNIQUE INDEX SICAS_OC.IDX_PLD_OBSERVACIONES_2 ON
    SICAS_OC.PLD_OBSERVACIONES(RFC);
    
ALTER TABLE SICAS_OC.PLD_OBSERVACIONES ADD(
    CONSTRAINT PK_PLD_OBSERVACIONES
    PRIMARY KEY (IDPROCESO,IDCONSEC)
    USING INDEX SICAS_OC.IDX_PLD_OBSERVACIONES_1);

GRANT SELECT,INSERT,UPDATE ON SICAS_OC.PLD_OBSERVACIONES TO ROL_MODIFICA_SICAS,ROL_CONSULTA_SICAS;

CREATE OR REPLACE PUBLIC SYNONYM SEQ_PLD_OBSERVACIONES FOR SICAS_OC.SEQ_PLD_OBSERVACIONES;

CREATE OR REPLACE PUBLIC SYNONYM PLD_OBSERVACIONES FOR SICAS_OC.PLD_OBSERVACIONES;

COMMENT ON COLUMN SICAS_OC.PLD_OBSERVACIONES.IDPROCESO IS '1 HISTORICO, 2 RELEVANTES, 3 PREOCUPANTES,4 INTERNAS, 5 ADMINLISTN,6 CRUCE HISTORICO 7 admriesg(emi-sin)' ;