grant select on SICAS_OC.TEMP_RECIBOS_PROV to ROL_CONSULTA_SICAS;
grant select, insert, update, delete, alter on SICAS_OC.TEMP_RECIBOS_PROV to ROL_MODIFICA_SICAS;

