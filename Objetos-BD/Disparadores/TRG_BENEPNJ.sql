CREATE OR REPLACE TRIGGER SICAS_OC.TRG_BENEFSIN_PNJ
  BEFORE INSERT ON BENEF_SIN
  FOR EACH ROW 
DECLARE
    vl_Texto    VARCHAR2(4000);
    vl_ErrorN   NUMBER;
    vl_ErrorC   VARCHAR2(4000);
BEGIN
  /*TRIGGER PARA MONITOREO DE LA TABLA BENEF_SIN
    FECHA CREACIN: 21/02/2025
    MODIFICO: LUIS ARGENIS REYNOSO ALVAREZ
    DESCRIPCIÓN: POR CADA PERSONA DADA DE ALTA COMO BENEFICIARIO EN BENESINI, SE DEBE AGREGAR EN PERSONA NATURAL JURIDICA
  */
 
	IF INSERTING THEN 
		BEGIN
			INSERT INTO SICAS_OC.PERSONA_NATURAL_JURIDICA (TIPO_DOC_IDENTIFICACION,
				NUM_DOC_IDENTIFICACION,NOMBRE,SEXO,FECNACIMIENTO,TELRES,EMAIL,
				FECSTS,FECINGRESO,TIPO_ID_TRIBUTARIA,NUM_TRIBUTARIO,TIPO_PERSONA,
				TELMOVIL,APELLIDO_MATERNO,APELLIDO_PATERNO,CURP,CODIGOZIP
			) VALUES (
				:NEW.TIPO_ID_TRIBUTARIO,:NEW.NUM_DOC_TRIBUTARIO,:NEW.NOMBRE,:NEW.SEXO,
				:NEW.FECNAC,:NEW.TELEFONO_LOCAL,:NEW.EMAIL,:NEW.FECALTA,:NEW.FECALTA,
				:NEW.TP_IDENTIFICACION,:NEW.NUM_IDENTIFICACION,:NEW.TIPO_PERSONA,:NEW.TELEFONO,
				:NEW.APELLIDO_MATERNO,:NEW.APELLIDO_PATERNO,:NEW.CURP,:NEW.CODIGOZIP
			);
		EXCEPTION
			WHEN DUP_VAL_ON_INDEX THEN
				NULL;
            WHEN OTHERS THEN
				RAISE_APPLICATION_ERROR(-20000,'ERROR: '||SQLERRM);
		END;
		
	END IF;  
	
	IF UPDATING THEN 
		BEGIN
			UPDATE SICAS_OC.PERSONA_NATURAL_JURIDICA 
			SET NOMBRE = :NEW.NOMBRE,
				SEXO = :NEW.SEXO,
				FECNACIMIENTO = :NEW.FECNAC,
				TELRES = :NEW.TELEFONO_LOCAL,
				EMAIL = :NEW.EMAIL,
				TIPO_ID_TRIBUTARIA = :NEW.TP_IDENTIFICACION,
				NUM_TRIBUTARIO = :NEW.NUM_IDENTIFICACION,
				TIPO_PERSONA = :NEW.TIPO_PERSONA,
				TELMOVIL = :NEW.TELEFONO,
				APELLIDO_MATERNO = :NEW.APELLIDO_MATERNO,
				APELLIDO_PATERNO = :NEW.APELLIDO_PATERNO,
				CURP = :NEW.CURP,
				CODIGOZIP = :NEW.CODIGOZIP
			WHERE TIPO_DOC_IDENTIFICACION = :OLD.TIPO_ID_TRIBUTARIO
				AND NUM_DOC_IDENTIFICACION = :OLD.NUM_DOC_TRIBUTARIO;
				
		EXCEPTION
			WHEN DUP_VAL_ON_INDEX THEN
				NULL;
            WHEN OTHERS THEN
				RAISE_APPLICATION_ERROR(-20000,'ERROR: '||SQLERRM);
		END;
		
	END IF;  

EXCEPTION
    WHEN OTHERS THEN 
      vl_ErrorN := SQLCODE;
      vl_ErrorC := 'Error con el disparador de BENEF_SIN, Contacte al administrador. '||SQLERRM;
      raise_application_error( -20000,vl_ErrorC);
END;
/

CREATE OR REPLACE PUBLIC SYNONYM TRG_BENEFSIN_PNJ FOR SICAS_OC.TRG_BENEFSIN_PNJ;
/